const LANG_KEY = 'lang';

function getCurrentLang() {
  const stored = localStorage.getItem(LANG_KEY);
  return stored === 'so' ? 'so' : 'en';
}

function t(key) {
  const lang = getCurrentLang();
  const table = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return table[key] !== undefined ? table[key] : (TRANSLATIONS.en[key] !== undefined ? TRANSLATIONS.en[key] : key);
}

function syncLangButton() {
  const btn = document.getElementById('langToggle');
  if (btn) btn.textContent = getCurrentLang() === 'so' ? 'SO' : 'EN';
}

function applyTranslations() {
  const lang = getCurrentLang();
  document.documentElement.lang = lang;

  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });

  // Dynamic package name on download.html
  const pkgName = document.getElementById('packageName');
  if (pkgName) {
    if (pkgName.dataset.pkg) {
      const base = pkgName.dataset.pkg.charAt(0).toUpperCase() + pkgName.dataset.pkg.slice(1);
      pkgName.textContent = base + ' ' + t('dl_package');
    } else {
      pkgName.textContent = t('dl_your_package');
    }
  }

  syncLangButton();
}

function toggleLang() {
  const next = getCurrentLang() === 'en' ? 'so' : 'en';
  localStorage.setItem(LANG_KEY, next);
  applyTranslations();
}

document.addEventListener('DOMContentLoaded', () => {
  applyTranslations();
  const langBtn = document.getElementById('langToggle');
  if (langBtn) langBtn.addEventListener('click', toggleLang);
});

export { t, getCurrentLang, applyTranslations, toggleLang };
